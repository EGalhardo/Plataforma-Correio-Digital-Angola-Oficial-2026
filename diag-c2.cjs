const { chromium } = require('playwright');
const APP='https://correio-digital-angola-oficial.vercel.app';
(async()=>{
 const b=await chromium.launch();
 const ctx=await b.newContext({viewport:{width:1440,height:900}});
 const p=await ctx.newPage();
 const logs=[];
 p.on('console',m=>logs.push(`[${m.type()}] ${m.text().slice(0,180)}`));
 p.on('pageerror',e=>logs.push('[pageerror] '+String(e.message||e).slice(0,220)));
 await p.goto(`${APP}/#/login`,{waitUntil:'networkidle'});
 await p.waitForTimeout(1500);
 await p.fill('input[name="cda-utilizador"]','002399714LA030');
 await p.fill('input[name="cda-senha"]','123456789');
 await p.click('button:has-text("ENTRAR NO PORTAL")');
 await p.waitForTimeout(5500);
 await p.route('**/assets/*.js',r=>/index-/.test(r.request().url())?r.continue():r.abort('failed'));
 await p.locator('button:has-text("Perfil")').first().click({timeout:8000}).catch(()=>{});
 await p.waitForTimeout(9000);
 console.log('--- registo do browser ---');
 [...new Set(logs)].slice(0,14).forEach(l=>console.log(' ',l));
 console.log('\n#root html:',(await p.evaluate(()=>document.querySelector('#root')?.innerHTML?.slice(0,200)))||'(vazio)');
 await ctx.close();await b.close();
})();
