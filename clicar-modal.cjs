const { chromium } = require('playwright');
const APP='https://correio-digital-angola-oficial.vercel.app';
const E=m=>new Promise(r=>setTimeout(r,m));
(async()=>{
 const b=await chromium.launch();
 const ctx=await b.newContext({viewport:{width:1400,height:950},locale:'pt-PT'});
 const p=await ctx.newPage();
 p.on('pageerror',e=>console.log('  ERRO JS:',String(e.message).slice(0,160)));
 p.on('console',m=>{if(m.type()==='error')console.log('  consola:',m.text().slice(0,140));});
 await p.goto(`${APP}/institucional/#/login`,{waitUntil:'networkidle'});await E(1300);
 await p.fill('input[name="cda-utilizador"]','AGT-LMM-01');await p.fill('input[name="cda-senha"]','123456789');
 await p.click('button:has-text("ENTRAR NO PORTAL")');await E(6000);
 await p.locator('button:has-text("Correio")').first().click();await E(2500);
 await p.locator('button:has-text("Nova Mensagem")').first().click();await E(2500);
 const dest=p.locator('input[placeholder*="BI" i]').first();
 await dest.click(); await dest.type('AGT-LMM-01',{delay:40}); await E(1500);
 await p.locator('input[placeholder*="tema" i]').first().click();
 await p.locator('input[placeholder*="tema" i]').first().type('AUTO-ENVIO-TESTE');
 await p.locator('textarea').first().click(); await p.locator('textarea').first().type('xx');
 await p.locator('button:has-text("Enviar Mensagem Oficial")').first().click(); await E(2500);
 console.log('modal aberto:',await p.locator('#btn-ok-modal-tipo-envio').count());
 // clicar exactamente no cartão Mensagem Normal
 const cartao=p.locator('[data-testid="popup-enviar-mensagem"] button').first();
 console.log('cartões:',await p.locator('[data-testid="popup-enviar-mensagem"] button').count());
 await cartao.click({force:true}); await E(2500);
 console.log('modal depois do clique no cartão:',await p.locator('#btn-ok-modal-tipo-envio').count());
 await p.screenshot({path:'test-artifacts/modal-1.png'});
 console.log('texto:',(await p.evaluate(()=>document.body.innerText)).replace(/\s+/g,' ').slice(0,400));
 await b.close();
})();
