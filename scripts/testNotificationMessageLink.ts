import assert from 'node:assert/strict';
import { notificationMessageId, notificationMessageKey, sameNotificationMessage } from '../src/utils/notificationMessageLink';
import { associarMensagem, obterListaCorrespondenciasNaoLidas } from '../src/utils/notificacoesAtalhos';
import type { AppNotification, Message } from '../src/types';
const id1 = 1794779395542674, id2 = id1 + 1;
const key = notificationMessageKey(id1, 'AGT-LMM');
assert.equal(notificationMessageId(key), id1);
assert.equal(notificationMessageId('invalid'), undefined);
assert.equal(notificationMessageId('cda:message:99999999999999999999:X'), undefined);
assert.equal(notificationMessageKey(-1, 'X'), undefined);
assert.equal(sameNotificationMessage(id1, id1), true);
assert.equal(sameNotificationMessage(id1, id2), false);
assert.equal(sameNotificationMessage(12345, 2345), true);
const msg = (id: number) => ({ id, org: 'x', unread: 1, status: 'Recebido', preview: 'assunto igual', details: { subject: 'assunto igual', body: '' } } as Message);
const notice = (id: number, messageId?: number) => ({ id, messageId, title: 'Aviso', message: 'assunto igual', targetTab: 'correspondencias', unread: true, time: '', type: 'info' } as AppNotification);
const a = msg(id1), b = msg(id2);
assert.equal(associarMensagem(notice(22, id2), [{tipo:'comunicados',m:a,funde:true}]), undefined, 'explicit link never falls back to same subject');
assert.equal(associarMensagem(notice(22), [{tipo:'comunicados',m:a,funde:true}])?.m.id, id1, 'legacy subject fallback');
const list = obterListaCorrespondenciasNaoLidas([a,b], [], false, [], [], [notice(21,id1),notice(22,id2)]);
assert.equal(list.length, 2, 'two different notices merge only with their own messages');
const list2 = obterListaCorrespondenciasNaoLidas([a], [], false, [], [], [notice(22,id2)]);
assert.equal(list2.length, 2, 'notice with explicit different message is not absorbed by same subject');
console.log('notification message link: PASS');
